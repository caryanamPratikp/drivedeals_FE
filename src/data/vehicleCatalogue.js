// 5. QUERY HELPERS (Strictly Deterministic & Cascading)
// ============================================================================

export function getBrands() {
  return BRANDS;
}

export function getModelsByBrand(brandId) {
  if (!brandId) return [];
  return MODELS.filter((m) => m.brandId.toLowerCase() === brandId.toLowerCase());
}

export function getModelById(modelId) {
  return MODELS.find((m) => m.id === modelId) || null;
}

export function getModelYears(modelId) {
  const model = getModelById(modelId);
  return model?.modelYears || [2026, 2025];
}

/**
 * Returns strictly the powertrains officially offered for the selected model.
 * Never includes Electric for an ICE model (e.g. XUV700 returns only ['PETROL', 'DIESEL']).
 * Never includes Petrol/Diesel for an EV model (e.g. XUV400 or BE 6 returns only ['ELECTRIC']).
 */
export function getPowertrains(modelId, year) {
  const model = getModelById(modelId);
  if (!model) return [];

  // Filter configurations for this model and (optional) year
  const configs = CONFIGURATIONS.filter(
    (c) => c.modelId === modelId && (!year || c.modelYear === Number(year))
  );

  const available = new Set(configs.map((c) => c.powertrain));

  // Intersect with the model's officially supported powertrains
  return (model.supportedPowertrains || []).filter((p) => available.has(p));
}

export function getEngineBatteryConfigs(modelId, year, powertrain) {
  if (!modelId || !powertrain) return [];
  const configs = CONFIGURATIONS.filter(
    (c) =>
      c.modelId === modelId &&
      (!year || c.modelYear === Number(year)) &&
      c.powertrain === powertrain
  );

  const distinct = [];
  const seen = new Set();
  for (const c of configs) {
    if (!seen.has(c.engineBattery)) {
      seen.add(c.engineBattery);
      distinct.push(c.engineBattery);
    }
  }
  return distinct;
}

export function getTransmissions(modelId, year, powertrain, engineBattery) {
  if (!modelId || !powertrain) return [];
  const configs = CONFIGURATIONS.filter(
    (c) =>
      c.modelId === modelId &&
      (!year || c.modelYear === Number(year)) &&
      c.powertrain === powertrain &&
      (!engineBattery || c.engineBattery === engineBattery)
  );

  const distinct = [];
  const seen = new Set();
  for (const c of configs) {
    if (!seen.has(c.transmission)) {
      seen.add(c.transmission);
      distinct.push(c.transmission);
    }
  }
  return distinct;
}

export function getVariants(modelId, year, powertrain, engineBattery, transmission) {
  if (!modelId || !powertrain) return [];
  return CONFIGURATIONS.filter(
    (c) =>
      c.modelId === modelId &&
      (!year || c.modelYear === Number(year)) &&
      c.powertrain === powertrain &&
      (!engineBattery || c.engineBattery === engineBattery) &&
      (!transmission || c.transmission === transmission)
  );
}

/**
 * Returns available exterior colours respecting variant restrictions.
 * E.g. Dual-tone finishes appear only when the selected variant is eligible.
 */
export function getColours(modelId, variantId) {
  if (!modelId) return [];
  const modelColours = COLOURS.filter((c) => c.modelId === modelId);

  if (!variantId) {
    // Return all colours available for this model across all trims
    return modelColours;
  }

  return modelColours.filter((c) => {
    if (!c.compatibleVariants) return true; // Available on all variants
    return c.compatibleVariants.includes(variantId);
  });
}

/**
 * Resolves the genuine vehicle image or provides an honest representative fallback.
 */
export function getVehicleImage(modelId, colourId, variantId) {
  const model = getModelById(modelId);
  const colour = COLOURS.find((c) => c.id === colourId && c.modelId === modelId);

  if (colour && colour.imageUrl) {
    return {
      imageUrl: colour.imageUrl,
      isVerified: Boolean(colour.isVerified),
      colourName: colour.name,
      modelName: model?.name,
      isDualTone: Boolean(colour.isDualTone),
    };
  }

  return {
    imageUrl: model?.defaultImage || '/cars/hyundai_creta.webp',
    isVerified: true,
    colourName: colour?.name || 'Default Exterior',
    modelName: model?.name,
    isDualTone: false,
  };
}
